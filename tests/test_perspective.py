def test_low_confidence_face_falls_back_and_reports_not_looking():
    gaze = _estimator()
    nose = (320.0, 240.0)
    # only the nose and one eye are confident → too few for PnP, and the heuristic needs a pair.
    person = _person(nose_px=nose, visible=(KP_NOSE, KP_LEFT_EYE))
    hazard = _bbox_at(nose[0] + 20.0, nose[1])

    assert gaze.head_pose(person) is None
    assert gaze.last_pose(person.track_id) is None
    assert gaze.looking_at(person, hazard) is False   # never claim a hazard was seen


def test_missing_nose_yields_no_pose_and_no_gaze():
    gaze = _estimator()
    person = _person(visible=(KP_LEFT_EYE, KP_RIGHT_EYE, KP_LEFT_EAR, KP_RIGHT_EAR))

    assert gaze.head_pose(person) is None
    assert gaze.looking_at(person, _bbox_at(320.0, 240.0)) is False


def test_all_zero_keypoints_do_not_raise():
    gaze = _estimator()
    person = PersonDetection(
        track_id=9,
        bbox=(0.0, 0.0, 10.0, 10.0),
        conf=0.5,
        keypoints=np.zeros((NUM_KEYPOINTS, 3), dtype=np.float32),
    )
    assert gaze.head_pose(person) is None
    assert gaze.looking_at(person, _bbox_at(5.0, 5.0)) is False


def test_degenerate_tiny_face_falls_back_to_heuristic():
    """A face a few pixels wide cannot support a 6-DoF fit, but the yaw ratio still works."""

    gaze = _estimator()
    kp = np.zeros((NUM_KEYPOINTS, 3), dtype=np.float32)
    kp[KP_NOSE] = [302.0, 240.0, 0.9]
    kp[KP_LEFT_EYE] = [303.0, 239.0, 0.9]
    kp[KP_RIGHT_EYE] = [299.0, 239.0, 0.9]
    person = PersonDetection(track_id=3, bbox=(290.0, 230.0, 312.0, 330.0), conf=0.8, keypoints=kp)

    pose = gaze.head_pose(person)
    assert pose is not None
    assert pose["method"] == "heuristic"
    assert pose["yaw_deg"] > 0.0            # nose right of the eye midline → turned image right
    assert gaze.last_pose(3) == pose
    # the fallback still produces a usable decision instead of raising.
    assert isinstance(gaze.looking_at(person, _bbox_at(500.0, 240.0)), bool)


def test_no_frame_size_means_no_pose_rather_than_a_crash():
    gaze = GazeEstimator(make_cfg())          # set_frame_size never called
    person = _person(yaw_deg=20.0)
    assert gaze.camera_matrix() is None
    assert gaze.head_pose(person)["method"] == "heuristic"
    assert gaze.looking_at(person, _bbox_at(400.0, 240.0)) is False


# --- interface / plumbing ------------------------------------------------------------------------


def test_calibrated_intrinsics_override_the_frame_size_guess():
    person = _person(yaw_deg=20.0, nose_px=(200.0, 300.0))

    # A wrong frame size gives a wrong pinhole guess, so the recovered yaw is wrong too.
    wrong = GazeEstimator(make_cfg())
    wrong.set_frame_size(1920, 1080)
    assert abs(wrong.head_pose(person)["yaw_deg"] - 20.0) > 5.0

    # Installing the intrinsics the keypoints were actually projected with fixes it.
    f = float(FRAME_W)
    cam = np.array(
        [[f, 0.0, FRAME_W / 2.0], [0.0, f, FRAME_H / 2.0], [0.0, 0.0, 1.0]], dtype=np.float64
    )
    wrong.set_intrinsics(cam, np.zeros(5))
    assert np.array_equal(wrong.camera_matrix(), cam)
    pose = wrong.head_pose(person)
    assert pose["method"] == "solvepnp"
    assert abs(pose["yaw_deg"] - 20.0) < 2.0


def test_pose_cache_is_bounded():
    gaze = _estimator()
    for tid in range(600):
        gaze.head_pose(_person(track_id=tid, yaw_deg=10.0))
    assert len(gaze._poses) <= 256
    assert len(gaze._pose_sig) <= 4 * 256
    assert gaze.last_pose(599) is not None      # newest survives
    assert gaze.last_pose(0) is None            # oldest evicted


def test_gaze_fn_is_the_bound_looking_at():
    gaze = _estimator()
    fn = gaze.gaze_fn()
    person = _person(yaw_deg=0.0, nose_px=(320.0, 240.0))
    assert fn(person, _bbox_at(330.0, 240.0)) == gaze.looking_at(person, _bbox_at(330.0, 240.0))


def test_ego_mode_uses_the_optical_axis_proxy():
    gaze = GazeEstimator(make_cfg(app={"perspective": "EGO"}))
    gaze.set_frame_size(FRAME_W, FRAME_H)
    blind = _person(visible=())                 # no face needed in EGO mode

    assert gaze.looking_at(blind, _bbox_at(FRAME_W / 2, FRAME_H / 2)) is True
    assert gaze.looking_at(blind, _bbox_at(FRAME_W - 5, FRAME_H - 5)) is False
    # an IMU yaw shifts the cone off the optical axis.
    gaze.set_orientation(28.0)
    assert gaze.looking_at(blind, _bbox_at(FRAME_W / 2, FRAME_H / 2)) is False
    assert gaze.looking_at(blind, _bbox_at(FRAME_W - 40, FRAME_H / 2)) is True


def test_both_mode_ors_the_two_perspectives():
    gaze = GazeEstimator(make_cfg(app={"perspective": "BOTH"}))
    gaze.set_frame_size(FRAME_W, FRAME_H)
    # worker in the corner looking away, hazard dead centre → EGO alone carries the decision.
    person = _person(yaw_deg=-40.0, nose_px=(600.0, 440.0))
    assert gaze.looking_at(person, _bbox_at(FRAME_W / 2, FRAME_H / 2)) is True
